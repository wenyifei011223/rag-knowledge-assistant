def text(s, x, y, color, scale=2):
    for ch in s:
        glyph = FONT.get(ch, FONT.get(' ', ['00000'] * 7))
        for row, bits in enumerate(glyph):
            for col, bit in enumerate(bits):
                if bit == '1':
                    rect(x + col * scale, y + row * scale, scale, scale, color)
        x += 6 * scale


